#!/usr/bin/env node
// Generates src/styles/tailwind-theme.css from design/tokens.json.
//
// Tailwind CSS 4 is configured in CSS. Every design token becomes a theme value that references
// the custom property declared in src/styles/tokens.css, so utilities follow the active theme at
// runtime. The block is `inline` (utilities use `var(--token)` directly) and `reference` (Tailwind
// emits no variables of its own: the tokens file is the only place where values live, and theme
// keys that share a name with a token, such as `--text-sm`, cannot shadow it).
//
// Spacing is strict: the 4px multiplier scale of Tailwind is disabled and only the six design
// steps exist, so `p-5` is 24px as in the design and `p-7` produces no utility at all.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const tokens = JSON.parse(readFileSync(resolve(root, "design/tokens.json"), "utf8"));

// Colour token → Tailwind colour name. Utilities: bg-<name>, text-<name>, border-<name>, ring-<name>.
const colorNames = {
  "--bg-app": "app",
  "--bg-raised": "raised",
  "--bg-hover": "hover",
  "--bg-selected": "selected",
  "--bg-active": "active",
  "--border": "line",
  "--border-strong": "line-strong",
  "--text": "fg",
  "--text-secondary": "fg-secondary",
  "--text-muted": "fg-muted",
  "--text-disabled": "fg-disabled",
  "--white": "white",
  "--accent": "accent",
  "--accent-text": "link",
  "--focus-ring": "focus",
  "--btn-primary-hover": "btn-primary-hover",
  "--btn-primary-active": "btn-primary-active",
  "--danger-hover": "danger-hover",
  "--danger-active": "danger-active",
  "--diff-add-bg": "add-bg",
  "--diff-add-fg": "add",
  "--diff-add-emphasis": "add-emphasis",
  "--diff-del-bg": "del-bg",
  "--diff-del-fg": "del",
  "--diff-del-emphasis": "del-emphasis",
  "--syntax-keyword": "syntax-keyword",
  "--syntax-function": "syntax-function",
  "--syntax-type": "syntax-type",
  "--syntax-string": "syntax-string",
  "--syntax-number": "syntax-number",
  "--syntax-comment": "syntax-comment",
  "--warn": "warn",
  "--danger": "danger",
  "--ok": "ok",
  "--info": "info",
  "--reviewed": "reviewed",
  "--shadow-color": "shadow",
};
for (let i = 1; i <= 8; i++) colorNames[`--lane-${i}`] = `lane-${i}`;
for (const kind of ["local", "current", "remote", "tag", "head", "stash"]) {
  colorNames[`--ref-${kind}`] = `ref-${kind}`;
}

// Size tokens that become spacing values: p-4, gap-2, w-sidebar, h-row-graph, min-w-detail-min, size-icon…
const spacingNames = {
  "--space-1": "1",
  "--space-2": "2",
  "--space-3": "3",
  "--space-4": "4",
  "--space-5": "5",
  "--space-6": "6",
  "--icon": "icon",
  "--row-graph": "row-graph",
  "--row-list": "row-list",
  "--row-tree": "row-tree",
  "--row-diff": "row-diff",
  "--row-hunk": "row-hunk",
  "--row-sidebar": "row-sidebar",
  "--panel-header": "panel-header",
  "--control": "control",
  "--bar-top": "bar-top",
  "--bar-status": "bar-status",
  "--sidebar-w": "sidebar",
  "--rail-w": "rail",
  "--detail-min": "detail-min",
};

// Type roles: text-sm, text-md, text-lg, text-xl, text-code, text-mono-sm (size and line height).
const typeRoles = [
  ["sm", "--text-sm", "--leading"],
  ["md", "--text-md", "--leading"],
  ["lg", "--text-lg", "--leading"],
  ["xl", "--text-xl", "--leading"],
  ["code", "--code-size", "--code-leading"],
  ["mono-sm", "--mono-sm", "--leading"],
];

function assertToken(group, token) {
  if (!(token in tokens[group])) throw new Error(`unknown ${group} token ${token}`);
}

const lines = [
  "/* Generated by scripts/generate-tailwind-theme.mjs from design/tokens.json. Do not edit by hand. */",
  "@theme inline reference {",
  "  /* Colours: the tokens only. The default palette is dropped so `bg-black` or",
  "     `text-red-500` compile to nothing, as the spacing scale drops `p-7`. */",
  "  --color-*: initial;",
];
for (const [token, name] of Object.entries(colorNames)) {
  assertToken("colors", token);
  lines.push(`  --color-${name}: var(${token});`);
}

lines.push("", "  /* Fonts: font-ui, font-mono */");
for (const token of Object.keys(tokens.fonts)) {
  lines.push(`  --font-${token.replace(/^--font-/, "")}: var(${token});`);
}

lines.push("", "  /* Type roles */");
for (const [name, size, leading] of typeRoles) {
  assertToken("sizes", size);
  assertToken("ratios", leading);
  lines.push(`  --text-${name}: var(${size});`, `  --text-${name}--line-height: var(${leading});`);
}

lines.push(
  "",
  "  /* Spacing and sizes: the design scale only, no 4px multiplier. Zero is on it: without it",
  "     `left-0`, `right-0` and `inset-0` generate nothing and an absolutely positioned row",
  "     of a virtualised list shrinks to its content. */",
  "  --spacing: initial;",
  "  --spacing-0: 0px;",
);
for (const [token, name] of Object.entries(spacingNames)) {
  assertToken("sizes", token);
  lines.push(`  --spacing-${name}: var(${token});`);
}

lines.push("", "  /* Radii and shadows */");
for (const name of ["sm", "md", "lg"]) {
  assertToken("sizes", `--radius-${name}`);
  lines.push(`  --radius-${name}: var(--radius-${name});`);
}
for (const token of Object.keys(tokens.shadows)) {
  lines.push(`  ${token}: var(${token});`);
}
lines.push("}", "");

const out = resolve(root, "src/styles/tailwind-theme.css");
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out}`);
